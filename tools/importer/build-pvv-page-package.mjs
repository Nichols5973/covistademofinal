/* Builds a CRX/Vault content package for the Purpose, Vision & Values page
   (crosswalk JCR) for upload via AEM Package Manager.
   Reuses the md2jcr XML already generated by the content import, and places it
   at /content/covistademo1/language-masters/en/purpose-vision-values. */
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const ROOT = '/workspace/current';
const TARGET = '/content/covistademo1/language-masters/en/purpose-vision-values';
const OUT = path.join(ROOT, 'migration-work/pvv-page-package');
const SRC_XML = path.join(ROOT, 'migration-work/jcr-content/our-story/purpose-vision-values.xml');

const xml = fs.readFileSync(SRC_XML, 'utf8');

// Write the page node .content.xml at the target JCR path.
const pageDir = path.join(OUT, 'jcr_root', TARGET.slice(1));
fs.mkdirSync(pageDir, { recursive: true });
fs.writeFileSync(path.join(pageDir, '.content.xml'), xml, 'utf8');
console.log(`wrote ${TARGET}/.content.xml (${xml.length} bytes)`);

// filter.xml — only the target page node.
const metaDir = path.join(OUT, 'META-INF/vault');
fs.mkdirSync(metaDir, { recursive: true });
fs.writeFileSync(path.join(metaDir, 'filter.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<workspaceFilter version="1.0">
  <filter root="${TARGET}"/>
</workspaceFilter>
`, 'utf8');
fs.writeFileSync(path.join(metaDir, 'properties.xml'), `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<!DOCTYPE properties SYSTEM "http://java.sun.com/dtd/properties.dtd">
<properties>
  <entry key="name">covista-pvv-page</entry>
  <entry key="group">covista</entry>
  <entry key="version">1.0</entry>
</properties>
`, 'utf8');

// zip it — use python's zipfile (the `zip` binary is not always available).
const zipPath = path.join(ROOT, 'tools/importer/packages/covista-pvv-page-content.zip');
try { fs.unlinkSync(zipPath); } catch { /* noop */ }
const py = [
  'import zipfile, os',
  `out=${JSON.stringify(zipPath)}`,
  `base=${JSON.stringify(OUT)}`,
  'z=zipfile.ZipFile(out,"w",zipfile.ZIP_DEFLATED)',
  'for root,_,files in os.walk(base):',
  '    for f in files:',
  '        full=os.path.join(root,f)',
  '        z.write(full, os.path.relpath(full, base))',
  'z.close()',
].join('\n');
execSync(`python3 -c ${JSON.stringify(py)}`, { stdio: 'inherit' });
console.log(`\nPackage: ${zipPath}`);
